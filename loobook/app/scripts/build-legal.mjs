// Turns loobook/legal/*.md into src/content/legal.ts so the app shows exactly
// the same text as the published documents. Run: npm run legal
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const legalDir = join(here, "..", "..", "legal");
const docs = { terms: "terms-of-service.md", privacy: "privacy-policy.md", guidelines: "community-guidelines.md" };

const strip = (s) => s.replace(/\*\*(.+?)\*\*/g, "$1").replace(/(^|\W)_(.+?)_(?=\W|$)/g, "$1$2").replace(/\[([^\]]+)\]\([^)]+\)/g, "$1");

function parse(md) {
  const blocks = [];
  let para = [];
  const flush = () => { if (para.length) { blocks.push({ t: "p", text: strip(para.join(" ")) }); para = []; } };
  for (const line of md.split("\n")) {
    const h = line.match(/^(#{1,3})\s+(.*)/);
    const li = line.match(/^\s*[-*]\s+(.*)/);
    if (h) { flush(); blocks.push({ t: h[1].length === 1 ? "h1" : "h2", text: strip(h[2]) }); }
    else if (li) { flush(); blocks.push({ t: "li", text: strip(li[1]) }); }
    else if (!line.trim()) flush();
    else para.push(line.trim());
  }
  flush();
  return blocks;
}

const out = Object.fromEntries(Object.entries(docs).map(([k, f]) => [k, parse(readFileSync(join(legalDir, f), "utf8"))]));
writeFileSync(join(here, "..", "src", "content", "legal.ts"),
  `// Generated by scripts/build-legal.mjs from loobook/legal/*.md. Do not edit by hand.\n` +
  `export type LegalBlock = { t: "h1" | "h2" | "p" | "li"; text: string };\n` +
  `export const LEGAL: Record<"terms" | "privacy" | "guidelines", LegalBlock[]> = ${JSON.stringify(out, null, 1)};\n`);
console.log("wrote src/content/legal.ts");
