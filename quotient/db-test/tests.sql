\set ON_ERROR_STOP on
\set A '00000000-0000-0000-0000-00000000000a'
\set B '00000000-0000-0000-0000-00000000000b'
\set C '00000000-0000-0000-0000-00000000000c'
insert into auth.users (id, email) values (:'A', 'ava@example.com'), (:'B', 'ben@example.com'), (:'C', 'cleo@example.com');

-- Each person creates their profile and stats, acting as themselves.
\set who :A
\set name 'Ava'
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'who', true);
insert into profiles (id, display_name) values (:'who', :'name');
insert into stats (user_id, level, streak) values (:'who', 3, 4);
insert into events (kind, payload) values ('qotd', '{"ok":1,"secs":40}');
commit;
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'B', true);
insert into profiles (id, display_name) values (:'B', 'Ben');
insert into stats (user_id, level) values (:'B', 2);
insert into events (kind, payload) values ('grid', '{"diff":"hard","secs":400}');
commit;
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'C', true);
insert into profiles (id, display_name) values (:'C', 'Cleo');
insert into stats (user_id, level) values (:'C', 5);
commit;

-- Codes were generated by the database, not chosen by the user.
select friend_code as code_b from profiles where id = :'B' \gset
select friend_code as code_c from profiles where id = :'C' \gset
select t((select count(distinct friend_code) from profiles) = 3 and :'code_b' ~ '^[A-HJ-NP-Z2-9]{8}$', 'friend codes are unique and well formed');

-- Strangers see nothing of each other.
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'A', true);
select t((select count(*) from profiles) = 1, 'Ava sees only her own profile before any friends');
select t((select count(*) from stats) = 1, 'Ava sees only her own stats');
select t((select count(*) from events) = 1, 'Ava sees only her own activity');
commit;

-- People cannot impersonate or befriend directly.
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'A', true);
do $$ begin
  begin insert into stats (user_id) values ('00000000-0000-0000-0000-00000000000c'); raise exception 'FAIL: wrote someone else''s stats'; exception when insufficient_privilege or check_violation or unique_violation then raise notice 'ok: cannot write another person''s stats'; end;
  begin insert into friendships (user_a, user_b, requested_by, status) values ('00000000-0000-0000-0000-00000000000a', '00000000-0000-0000-0000-00000000000c', '00000000-0000-0000-0000-00000000000a', 'accepted'); raise exception 'FAIL: inserted a friendship directly'; exception when insufficient_privilege then raise notice 'ok: friendships cannot be written directly'; end;
  begin update profiles set friend_code = 'AAAAAAAA' where id = '00000000-0000-0000-0000-00000000000a'; raise exception 'FAIL: changed own friend code'; exception when insufficient_privilege then raise notice 'ok: friend codes cannot be changed by hand'; end;
end $$;
select t(send_friend_request(:'code_b') = 'sent', 'Ava sends Ben a request by code');
select t(send_friend_request(:'code_b') = 'already_sent', 'sending twice does not duplicate');
select t((select count(*) from profiles) = 2, 'a pending request shows Ben''s name to Ava');
select t((select count(*) from stats) = 1, 'but not Ben''s stats before he accepts');
commit;
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'C', true);
do $$ begin perform send_friend_request('ZZZZZZZZ'); raise exception 'FAIL: unknown code accepted'; exception when raise_exception then raise notice 'ok: unknown codes are refused'; end $$;
commit;

-- Ben accepts; now they share stats and activity, and Cleo still sees neither.
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'B', true);
select respond_friend_request(:'A', true);
select t((select count(*) from stats) = 2, 'after accepting, Ben sees Ava''s stats');
select t((select count(*) from events) = 2, 'and her activity');
select id as ava_event from events where user_id = :'A' \gset
insert into cheers (event_id, emoji) values (:ava_event, '🔥');
select t((select count(*) from cheers) = 1, 'Ben cheers Ava''s result');
commit;
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'C', true); select set_config('test.ev', :'ava_event', true);
select t((select count(*) from stats) = 1 and (select count(*) from events) = 0 and (select count(*) from cheers) = 0, 'Cleo sees none of Ava and Ben''s data');
\set ev :ava_event
do $$ begin
  execute format('insert into cheers (event_id, emoji) values (%s, %L)', current_setting('test.ev'), '👏');
  raise exception 'FAIL: Cleo cheered activity she cannot see';
exception when insufficient_privilege then raise notice 'ok: Cleo cannot cheer activity she cannot see, even by its id';
end $$;
commit;

-- Turning sharing off hides activity but keeps the friendship and stats.
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'A', true);
update profiles set share_activity = false where id = :'A';
commit;
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'B', true);
select t((select count(*) from events where user_id = :'A') = 0, 'with sharing off, Ava''s activity is hidden from Ben');
select t((select count(*) from stats) = 2, 'but her stats still show');
commit;

-- Blocking ends the friendship, and the blocked person cannot see it or send again.
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'B', true);
select block_user(:'A');
commit;
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'A', true);
select t((select count(*) from stats) = 1 and (select count(*) from profiles) = 1, 'after Ben blocks Ava she no longer sees him');
select t((select count(*) from friendships) = 0, 'and cannot see that she was blocked');
do $$ declare code text; begin select friend_code into code from profiles limit 0; perform send_friend_request((select friend_code from public.profiles where id = '00000000-0000-0000-0000-00000000000b')); raise exception 'FAIL: request through a block'; exception when raise_exception then raise notice 'ok: requests cannot get past a block'; end $$;
commit;

-- Reports and account deletion.
begin; set local role authenticated; select set_config('request.jwt.claim.sub', :'C', true);
insert into reports (reported, reason) values (:'A', 'test report');
select t((select count(*) from profiles) = 1, 'reporters cannot read reports or other profiles');
select delete_account();
commit;
select t(not exists (select 1 from auth.users where id = :'C') and not exists (select 1 from profiles where id = :'C') and not exists (select 1 from stats where user_id = :'C'), 'deleting an account removes the user and all their data');
